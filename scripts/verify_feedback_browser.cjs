/* Requires an isolated local server with no existing saves. */
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const [url, evidence, expectedVersion] = process.argv.slice(2);
  assert.ok(url && evidence, 'Usage: node scripts/verify_feedback_browser.cjs URL EVIDENCE_DIR [BUILD_VERSION]');
  assert.ok(['127.0.0.1','localhost'].includes(new URL(url).hostname));
  fs.mkdirSync(evidence,{recursive:true});
  const browser = await chromium.launch({executablePath:process.env.NBA_GM_TEST_CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  const report = {checks:[],page_errors:[]};
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
    await context.route('**/*', route => ['127.0.0.1','localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort('internetdisconnected'));
    const page = await context.newPage();
    const sentNotes = [];
    page.on('pageerror',error=>report.page_errors.push(String(error)));
    page.on('request',request=>{if(request.method()==='POST' && request.postData()?.includes('feedback-private-note')) sentNotes.push(request.url());});
    const ready = () => page.waitForFunction(()=>!state.hydrating && !state.busy,null,{timeout:60000});
    const check = name => { report.checks.push(name); console.log(name); };
    await page.goto(url);
    await page.waitForFunction(()=>document.querySelector('#teamSelect').options.length>1);
    await ready();
    assert.equal(await page.locator('#startupSaveSelect option').evaluateAll(options=>options.filter(option=>option.value).length),0,'Refusing existing saves');
    await page.locator('#startupReportIssue').click();
    await page.locator('[name="summary"]').fill('feedback-private-note: video');
    await page.waitForFunction(()=>state.modal.report.runtime_available);
    if(expectedVersion) assert.equal(await page.evaluate(()=>state.modal.report.runtime.version),expectedVersion);
    assert.equal(await page.locator('#app').evaluate(el=>el.inert),true);
    await page.locator('[name="summary"]').focus();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.hasAttribute('data-close-modal')),true);
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.type),'submit');
    await page.screenshot({path:path.join(evidence,'issue-desktop.png')});
    const downloadPromise=page.waitForEvent('download');
    await page.locator('[data-issue-report-form] button[type="submit"]').click();
    const download=await downloadPromise;
    await download.saveAs(path.join(evidence,'startup-issue.json'));
    const startup=JSON.parse(fs.readFileSync(path.join(evidence,'startup-issue.json'),'utf8'));
    assert.equal(startup.notes.summary,'feedback-private-note: video');
    assert.equal(startup.context.screen,'save_selection');
    assert.equal(startup.runtime_available,true);
    assert.deepEqual(sentNotes,[]);
    check('save-screen download is local, authenticated metadata is available, keyboard focus is trapped');
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(()=>state.modal),null);
    assert.equal(await page.evaluate(()=>document.activeElement.id),'startupReportIssue');

    await page.route('**/api/action',route=>route.request().postDataJSON()?.action==='diagnostic_runtime' ? route.fulfill({status:503,contentType:'application/json',body:'{"ok":false,"error":"/Users/private/token"}'}) : route.continue());
    await page.setViewportSize({width:390,height:844});
    await page.locator('#startupReportIssue').click();
    await page.locator('[name="summary"]').fill('Offline connection');
    await page.locator('[name="steps"]').fill('Open save screen');
    await page.screenshot({path:path.join(evidence,'issue-mobile.png')});
    const bounds=await page.locator('.issue-report-form').evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth,left:el.getBoundingClientRect().left,right:el.getBoundingClientRect().right}));
    assert.ok(bounds.scroll<=bounds.width+1 && bounds.left>=0 && bounds.right<=390);
    const offlinePromise=page.waitForEvent('download');
    await page.locator('[data-issue-report-form] button[type="submit"]').click();
    await (await offlinePromise).saveAs(path.join(evidence,'offline-issue.json'));
    const offline=JSON.parse(fs.readFileSync(path.join(evidence,'offline-issue.json'),'utf8'));
    assert.equal(offline.runtime_available,false);
    assert.ok(!JSON.stringify(offline).includes('/Users/private/token'));
    check('unavailable metadata still permits a usable mobile report without raw server errors');
    await page.keyboard.press('Escape');
    await page.unroute('**/api/action');
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('[data-team-value="GSW"]').click();
    await page.locator('#saveName').fill('feedback_isolated');
    await page.locator('#createSave').click();
    await page.locator('[data-tutorial-action="skip"]').waitFor({timeout:60000});
    await page.locator('[data-tutorial-action="skip"]').click();
    await ready();
    const before=await page.evaluate(()=>({date:state.home.save.current_date,phase:state.home.save.phase,record:state.home.save.user_team_record}));
    const savePath=await page.evaluate(()=>state.currentSave);
    await page.locator('[data-dashboard-settings]:visible').first().click();
    await page.locator('[data-report-issue]').click();
    await page.waitForFunction(()=>state.modal.report.runtime_available);
    await page.locator('[name="summary"]').fill('Minutes feedback');
    const gamePromise=page.waitForEvent('download');
    await page.locator('[data-issue-report-form] button[type="submit"]').click();
    await (await gamePromise).saveAs(path.join(evidence,'game-issue.json'));
    const game=JSON.parse(fs.readFileSync(path.join(evidence,'game-issue.json'),'utf8'));
    assert.equal(game.context.screen,'game');
    assert.equal(game.context.date,before.date);
    assert.ok(game.context.visible_cards.length>0);
    assert.ok(game.recent_actions.some(row=>row.action==='create_save' && row.succeeded));
    assert.ok(!JSON.stringify(game).includes(savePath));
    assert.ok(!JSON.stringify(game).includes('feedback_isolated'));
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(()=>state.modal.kind),'dashboardSettings');
    await page.keyboard.press('Escape');
    assert.deepEqual(await page.evaluate(()=>({date:state.home.save.current_date,phase:state.home.save.phase,record:state.home.save.user_team_record})),before);
    assert.deepEqual(sentNotes,[]);
    check('Settings report includes gameplay context but not save names or paths, and leaves gameplay unchanged');
    assert.deepEqual(report.page_errors,[]);
    report.status='passed';
  } catch(error) { report.status='failed'; report.error=String(error); process.exitCode=1; }
  finally { fs.writeFileSync(path.join(evidence,'report.json'),JSON.stringify(report,null,2)); await browser.close(); console.log(JSON.stringify(report,null,2)); }
})();
