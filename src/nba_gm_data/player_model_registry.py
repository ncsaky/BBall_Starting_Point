def validate_registry(registry: dict | None = None) -> None:
    registry = definition_registry() if registry is None else registry
    inputs, outputs = registry["inputs"], registry["outputs"]
    nodes = {row["id"]: row for row in inputs + outputs}
    if len(nodes) != 153 or len(inputs) != 94 or len(outputs) != 59:
        raise ValueError("Expected exactly 94 inputs and 59 derived/role definitions")
    expected_inputs = {f"{prefix}{i:02d}" for prefix, count in (("P", 12), ("S", 46), ("T", 18)) for i in range(1, count + 1)}
    expected_inputs |= {f"F{i:02d}.{part}" for i in range(1, 10) for part in ("recognition", "execution")}
    expected_outputs = {f"{prefix}{i:02d}" for prefix, count in (("C", 37), ("R", 22)) for i in range(1, count + 1)}
    if {row["id"] for row in inputs} != expected_inputs or {row["id"] for row in outputs} != expected_outputs:
        raise ValueError("Catalogue IDs differ from the approved inventory")
    if any(row.get("dependencies") for row in inputs):
        raise ValueError("Derived fields cannot feed raw inputs")
    summaries = {row["id"] for row in outputs if row["summary_only"]}
    visiting, visited = set(), set()

    def visit(key):
        if key in visiting:
            raise ValueError(f"Dependency cycle at {key}")
        if key in visited:
            return
        visiting.add(key)
        for dep in nodes[key].get("dependencies", []):
            if dep not in nodes:
                raise ValueError(f"Unknown dependency {dep}")
            if dep in summaries:
                raise ValueError(f"Summary feedback: {key} consumes {dep}")
            visit(dep)
        visiting.remove(key)
        visited.add(key)

    for key in nodes:
        visit(key)
    if any(row["trainable"] for row in outputs):
        raise ValueError("Derived outputs cannot be independently trained")
